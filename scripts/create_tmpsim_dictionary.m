function create_tmpsim_dictionary(dictionaryPath)
%CREATE_TMPSIM_DICTIONARY Creates the project's Simulink data dictionary.

if nargin == 0
    projectRoot = fileparts(fileparts(mfilename('fullpath')));
    dictionaryPath = fullfile(projectRoot, 'model', 'tmpsim_online.sldd');
end

dictionaryFolder = fileparts(dictionaryPath);
if ~isfolder(dictionaryFolder)
    mkdir(dictionaryFolder);
end

if ~isfile(dictionaryPath)
    Simulink.data.dictionary.create(dictionaryPath);
end

dictionary = Simulink.data.dictionary.open(dictionaryPath);
cleanupDictionary = onCleanup(@() close(dictionary));
designData = getSection(dictionary, 'Design Data');

busNames = ["RefBus", "MeasBus", "ErrBus", "HistoryBus", ...
    "RiskRawBus", "RiskBus", "MPCParamBus", "CmdBus"];
for busName = busNames
    bus = Simulink.Bus;
    bus.Description = sprintf('%s signal contract.', busName);
    upsertEntry(designData, char(busName), bus);
end

measBus = createBus('Vehicle measurements normalized to SI units.', { ...
    'x',                'double', 1, 'm',     'Vehicle global x position'; ...
    'y',                'double', 1, 'm',     'Vehicle global y position'; ...
    'yaw',              'double', 1, 'rad',   'Vehicle heading'; ...
    'vx',               'double', 1, 'm/s',   'Vehicle longitudinal speed'; ...
    'vy',               'double', 1, 'm/s',   'Vehicle lateral speed'; ...
    'yaw_rate',         'double', 1, 'rad/s', 'Vehicle yaw rate'; ...
    'beta',             'double', 1, 'rad',   'Vehicle sideslip angle'; ...
    'ay',               'double', 1, 'm/s^2', 'Vehicle lateral acceleration'; ...
    'delta_meas',       'double', 1, 'rad',   'Average measured front road-wheel angle'; ...
    'ax_meas',          'double', 1, 'm/s^2', 'Vehicle longitudinal acceleration'; ...
    'delta_rate_meas',  'double', 1, 'rad/s', 'Measured front-wheel angle rate'; ...
    'meas_valid',       'boolean', 1, '',     'True when all mapped measurements are finite'});
upsertEntry(designData, 'MeasBus', measBus);

refBus = createBus('Reference path state at the current path index.', { ...
    'x_ref',       'double', 1, 'm',   'Reference global x position'; ...
    'y_ref',       'double', 1, 'm',   'Reference global y position'; ...
    'psi_ref',     'double', 1, 'rad', 'Reference heading'; ...
    'kappa_ref',   'double', 1, '1/m', 'Reference curvature'; ...
    'v_ref_base',  'double', 1, 'm/s', 'Baseline reference speed'; ...
    'path_idx',    'uint32', 1, '',    'Current nearest reference-path index'; ...
    'ref_valid',   'boolean', 1, '',   'True when the reference path is valid'});
upsertEntry(designData, 'RefBus', refBus);

errBus = createBus('Vehicle tracking errors in the Frenet reference frame.', { ...
    'e_y',          'double', 1, 'm',     'Lateral tracking error'; ...
    'e_psi',        'double', 1, 'rad',   'Heading tracking error'; ...
    'e_y_rate',     'double', 1, 'm/s',   'Lateral-error rate'; ...
    'e_psi_rate',   'double', 1, 'rad/s', 'Heading-error rate'; ...
    'yaw_ref',      'double', 1, 'rad',   'Reference heading retained for logging'; ...
    'kappa_ref',    'double', 1, '1/m',   'Reference curvature retained for control'; ...
    'v_ref_base',   'double', 1, 'm/s',   'Baseline reference speed retained for control'; ...
    'err_valid',    'boolean', 1, '',      'True when tracking errors are valid'});
upsertEntry(designData, 'ErrBus', errBus);

historyBus = createBus('Fixed-size Transformer feature history.', { ...
    'window',          'double', [16 14], '',  'Feature history ordered from oldest to newest'; ...
    'latest_feature',  'double', [1 14],  '',  'Current raw feature row'; ...
    'window_ready',    'boolean', 1,       '',  'True when the history window is full'; ...
    'history_len',     'uint16', 1,        '',  'Number of valid rows in the history window'; ...
    'sample_time',     'double', 1,        's', 'History sample period'});
upsertEntry(designData, 'HistoryBus', historyBus);

riskRawBus = createBus('Raw Transformer risk inference outputs.', { ...
    'r_low_raw',                  'double', 1, '',   'Raw aggregate risk'; ...
    'r_ey_raw',                   'double', 1, '',   'Raw lateral-error risk'; ...
    'r_stab_raw',                 'double', 1, '',   'Raw stability risk'; ...
    'k_v_raw',                    'double', 1, '',   'Raw speed scaling factor'; ...
    'risk_raw_valid',             'boolean', 1, '',  'True when raw risk output is valid'; ...
    'risk_source_id',             'uint8', 1, '',    '0 for rule fallback and 1 for Transformer'; ...
    'transformer_status_code',    'uint8', 1, '',    'Transformer execution status'; ...
    'transformer_latency_ms',     'double', 1, 'ms', 'Transformer inference latency'});
upsertEntry(designData, 'RiskRawBus', riskRawBus);

riskBus = createBus('Bounded and filtered risk outputs.', { ...
    'r_low',            'double', 1, '', 'Filtered aggregate risk'; ...
    'r_ey',             'double', 1, '', 'Filtered lateral-error risk'; ...
    'r_stab',           'double', 1, '', 'Filtered stability risk'; ...
    'k_v',              'double', 1, '', 'Filtered speed scaling factor'; ...
    'risk_valid',       'boolean', 1, '', 'True when risk output is valid'; ...
    'degraded_mode',    'boolean', 1, '', 'True when the supervisor is degraded'; ...
    'risk_source_id',   'uint8', 1, '',   '0 for rule fallback and 1 for Transformer'});
upsertEntry(designData, 'RiskBus', riskBus);

mpcParamBus = createBus('Risk-adapted lateral MPC weights and constraints.', { ...
    'q_y',              'double', 1, '',      'Lateral-error weight'; ...
    'q_psi',            'double', 1, '',      'Heading-error weight'; ...
    'q_beta',           'double', 1, '',      'Sideslip-angle weight'; ...
    'q_r',              'double', 1, '',      'Yaw-rate weight'; ...
    'r_delta',          'double', 1, '',      'Steering-angle penalty'; ...
    'r_d_delta',        'double', 1, '',      'Steering-rate penalty'; ...
    'beta_max',         'double', 1, 'rad',   'Sideslip-angle limit'; ...
    'yaw_rate_max',     'double', 1, 'rad/s', 'Yaw-rate limit'; ...
    'ay_max',           'double', 1, 'm/s^2', 'Lateral-acceleration limit'; ...
    'delta_max',        'double', 1, 'rad',   'Front-wheel angle limit'; ...
    'delta_rate_max',   'double', 1, 'rad/s', 'Front-wheel angle-rate limit'; ...
    'v_ref_adapt',      'double', 1, 'm/s',   'Risk-adapted reference speed'; ...
    'param_valid',      'boolean', 1, '',      'True when all MPC parameters are valid'});
upsertEntry(designData, 'MPCParamBus', mpcParamBus);

cmdBus = createBus('Validated high-level vehicle control commands.', { ...
    'delta_cmd',        'double', 1, 'rad',   'Commanded front-wheel angle'; ...
    'ax_cmd',           'double', 1, 'm/s^2', 'Commanded longitudinal acceleration'; ...
    'cmd_valid',        'boolean', 1, '',      'True when the command is valid'; ...
    'hold_last_cmd',    'boolean', 1, '',      'True when the adapter must hold the previous command'; ...
    'control_mode_id',  'uint8', 1, '',        '0 PID, 1 Fixed MPC, 2 Rule-risk MPC, 3 Transformer-MPC'});
upsertEntry(designData, 'CmdBus', cmdBus);

saveChanges(dictionary);
clear cleanupDictionary
end

function upsertEntry(designData, entryName, entryValue)
if exist(designData, entryName)
    setValue(getEntry(designData, entryName), entryValue);
else
    addEntry(designData, entryName, entryValue);
end
end

function bus = createBus(description, elementSpecs)
elementCount = size(elementSpecs, 1);
elements(1, elementCount) = Simulink.BusElement;
for elementIndex = 1:elementCount
    element = Simulink.BusElement;
    element.Name = elementSpecs{elementIndex, 1};
    element.DataType = elementSpecs{elementIndex, 2};
    element.Dimensions = elementSpecs{elementIndex, 3};
    element.Unit = elementSpecs{elementIndex, 4};
    element.Description = elementSpecs{elementIndex, 5};
    elements(elementIndex) = element;
end

bus = Simulink.Bus;
bus.Description = description;
bus.Elements = elements;
end
